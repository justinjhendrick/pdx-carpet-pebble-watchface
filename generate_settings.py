#!/bin/env python3
import json
from typing import Any, TypeAlias
from pathlib import Path
from dataclasses import dataclass
from enum import Enum
from pprint import pprint
from copy import deepcopy

ROOT = Path(__file__).resolve().parent

Json: TypeAlias = Any

class ClayType(Enum):
    COLOR = "color"
    TOGGLE = "toggle"

    def c_type(self) -> str:
        if self == ClayType.COLOR:
            return "GColor";
        elif self == ClayType.TOGGLE:
            return "bool";

@dataclass
class Clay:
    typ: ClayType
    default: str | bool
    message_key: str

def parse_clay_object(v: Json) -> Clay:
    typ = ClayType(v["type"])
    if typ == ClayType.TOGGLE:
        default = bool(v["defaultValue"])
    else:
        default = v["defaultValue"]
    return Clay(
        typ,
        default,
        v["messageKey"],
    )

def parse_clay_objects(v: Json) -> list[Clay]:
    if isinstance(v, list):
        result = []
        for elem in v:
            result += parse_clay_objects(elem)
        return result
    if isinstance(v, dict):
        if v["type"] == "section":
            return parse_clay_objects(v["items"])
        elif v["type"] in ("heading", "submit"):
            return []
        return [parse_clay_object(v)]
    raise ValueError(f"Did not expect '{v}'")

def write_message_keys(clays: list[Clay], old_package_contents: Json) -> Json:
    keys = sorted(clay.message_key for clay in clays)
    new_package_contents = deepcopy(old_package_contents)
    new_package_contents["pebble"]["messageKeys"] = keys
    return new_package_contents

def write_c_files(folder: Path, clays: list[Clay]) -> None:
    header = []
    header.append(f"// GENERATED BY {Path(__file__).name}\n")
    header.append("#pragma once\n")
    for clay in clays:
        header.append(f"extern {clay.typ.c_type()} {clay.message_key};");
    header.append("")
    header.append("void init_settings();")

    src = []
    src.append(f"// GENERATED BY {Path(__file__).name}\n")
    src.append("#include <pebble.h>")
    src.append('#include "settings.h"\n')
    for clay in clays:
        if clay.typ == ClayType.COLOR:
            src.append(f"{clay.typ.c_type()} {clay.message_key} = GColorFromHEX(0x{clay.default});")
        elif clay.typ == ClayType.TOGGLE:
            src.append(f"{clay.typ.c_type()} {clay.message_key} = {str(clay.default).lower()};")
    src.append("")

    src.append("static void load_settings() {")
    for clay in clays:
        src.append(f"  if (persist_exists(MESSAGE_KEY_{clay.message_key})) {{")
        if clay.typ == ClayType.COLOR:
            src.append(f"    {clay.message_key}.argb = persist_read_int(MESSAGE_KEY_{clay.message_key});")
        elif clay.typ == ClayType.TOGGLE:
            src.append(f"    {clay.message_key} = persist_read_bool(MESSAGE_KEY_{clay.message_key});")
        else:
            raise ValueError(f"Unexpected {clay.typ}")
        src.append("  }")
    src.append("}\n");

    src.append("static void inbox_received_handler(DictionaryIterator* iter, void* callback) {")
    src.append("  Tuple* t;")
    for clay in clays:
        src.append(f"  t = dict_find(iter, MESSAGE_KEY_{clay.message_key});")
        src.append("  if (t) {")
        if clay.typ == ClayType.COLOR:
            src.append(f"    {clay.message_key} = GColorFromHEX(t->value->int32);")
            src.append(f"    persist_write_int(MESSAGE_KEY_{clay.message_key}, {clay.message_key}.argb);")
        elif clay.typ == ClayType.TOGGLE:
            src.append(f"    {clay.message_key} = t->value->int32;")
            src.append(f"    persist_write_bool(MESSAGE_KEY_{clay.message_key}, {clay.message_key});")
        else:
            raise ValueError(f"Unexpected {clay.typ}")
        src.append("  }")
    src.append("  ((void (*)(void))callback)();")
    src.append("}\n");

    src.append("void init_settings() {")
    src.append("  load_settings();")
    src.append("  app_message_register_inbox_received(inbox_received_handler);")
    src.append("  app_message_open(1024, 64);")
    src.append("}\n");

    (folder / "settings.h").write_text("\n".join(header))
    (folder / "settings.c").write_text("\n".join(src))


def main() -> None:
    package_file = ROOT / "package.json"
    package = json.loads(package_file.read_text())
    raw_clay = json.loads((ROOT / "src" / "pkjs" / "config.json").read_text())
    clays = parse_clay_objects(raw_clay)
    new_package = write_message_keys(clays, package)
    package_file.write_text(json.dumps(new_package, indent=2))
    write_c_files(ROOT / "src" / "c", clays)


if __name__ == "__main__":
    main()
